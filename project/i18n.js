const I18N = {
  en: EN,
  ar: AR
};

// detect default
function detectLang() {
  try {
    const saved = localStorage.getItem('bareeq.lang');
    if (saved === 'en' || saved === 'ar') return saved;
  } catch {}
  const browser = (navigator.language || 'en').toLowerCase();
  return browser.startsWith('ar') ? 'ar' : 'en';
}
const LangCtx = React.createContext({
  lang: 'en',
  t: k => k,
  setLang: () => {}
});
function LangProvider({
  children
}) {
  const [lang, setLangState] = React.useState(detectLang);
  React.useEffect(() => {
    document.documentElement.lang = lang;
    document.documentElement.dir = lang === 'ar' ? 'rtl' : 'ltr';
    document.title = I18N[lang].meta.title;
    try {
      localStorage.setItem('bareeq.lang', lang);
    } catch {}
  }, [lang]);
  const setLang = l => setLangState(l);
  const toggle = () => setLangState(l => l === 'en' ? 'ar' : 'en');
  const t = React.useCallback((path, fallback) => {
    const parts = path.split('.');
    let cur = I18N[lang];
    for (const p of parts) {
      if (cur && typeof cur === 'object' && p in cur) cur = cur[p];else return fallback !== undefined ? fallback : path;
    }
    return cur;
  }, [lang]);
  return /*#__PURE__*/React.createElement(LangCtx.Provider, {
    value: {
      lang,
      t,
      setLang,
      toggle
    }
  }, children);
}
function useI18n() {
  return React.useContext(LangCtx);
}
Object.assign(window, {
  LangProvider,
  LangCtx,
  useI18n,
  I18N
});
